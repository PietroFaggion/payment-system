--------------- accounts START ----------------
-- DROP TABLE IF EXIST
DROP TABLE IF EXISTS accounts CASCADE;

-- CREATE TABLE
CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    owner_name TEXT NOT NULL,
    balance NUMERIC(19,4) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0
);

-- COMMENT
COMMENT ON TABLE accounts IS 'Account master data';
COMMENT ON COLUMN accounts.id IS 'PK: surrogate identifier for account';
COMMENT ON COLUMN accounts.owner_name IS 'Account owner name';
COMMENT ON COLUMN accounts.balance IS 'Current account balance';
COMMENT ON COLUMN accounts.currency IS 'ISO 4217 currency code';
COMMENT ON COLUMN accounts.created_at IS 'Audit: creation timestamp in UTC';
COMMENT ON COLUMN accounts.version IS 'Optimistic locking version';

-- CONSTRAINT
ALTER TABLE accounts
    ADD CONSTRAINT accounts_pk PRIMARY KEY (id);
ALTER TABLE accounts
    ADD CONSTRAINT accounts_balance_non_negative_ck CHECK (balance >= 0);
ALTER TABLE accounts
    ADD CONSTRAINT accounts_currency_len_ck CHECK (char_length(currency) = 3);

-- CREATE INDEX
-- (none, PK covers identity lookups)

-- TRIGGER
-- (none)
