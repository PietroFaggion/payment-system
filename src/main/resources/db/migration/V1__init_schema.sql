--------------- transactions START ----------------
-- DROP TABLE IF EXIST
DROP TABLE IF EXISTS transactions CASCADE;

-- CREATE TABLE
CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sender_account_id BIGINT NOT NULL,
    receiver_account_id BIGINT NOT NULL,
    amount NUMERIC(19,4) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(16) NOT NULL,
    idempotency_key TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    failure_reason TEXT
);

-- COMMENT
COMMENT ON TABLE transactions IS 'Payment transaction records';
COMMENT ON COLUMN transactions.id IS 'PK: surrogate identifier for transaction';
COMMENT ON COLUMN transactions.sender_account_id IS 'FK to sender account';
COMMENT ON COLUMN transactions.receiver_account_id IS 'FK to receiver account';
COMMENT ON COLUMN transactions.amount IS 'Transferred amount';
COMMENT ON COLUMN transactions.currency IS 'ISO 4217 currency code';
COMMENT ON COLUMN transactions.status IS 'Transaction status (PENDING/COMPLETED/FAILED)';
COMMENT ON COLUMN transactions.idempotency_key IS 'Unique idempotency key for deduplication';
COMMENT ON COLUMN transactions.created_at IS 'Audit: creation timestamp in UTC';
COMMENT ON COLUMN transactions.updated_at IS 'Audit: last update timestamp in UTC';
COMMENT ON COLUMN transactions.failure_reason IS 'Optional failure reason when status is FAILED';

-- CONSTRAINT
ALTER TABLE transactions
    ADD CONSTRAINT transactions_pk PRIMARY KEY (id);
ALTER TABLE transactions
    ADD CONSTRAINT transactions_sender_account_fk FOREIGN KEY (sender_account_id)
        REFERENCES accounts (id);
ALTER TABLE transactions
    ADD CONSTRAINT transactions_receiver_account_fk FOREIGN KEY (receiver_account_id)
        REFERENCES accounts (id);
ALTER TABLE transactions
    ADD CONSTRAINT transactions_amount_positive_ck CHECK (amount > 0);
ALTER TABLE transactions
    ADD CONSTRAINT transactions_currency_len_ck CHECK (char_length(currency) = 3);
ALTER TABLE transactions
    ADD CONSTRAINT transactions_status_ck CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED'));
ALTER TABLE transactions
    ADD CONSTRAINT transactions_idempotency_key_uk UNIQUE (idempotency_key);

-- CREATE INDEX
CREATE INDEX transactions_sender_account_idx ON transactions (sender_account_id);
CREATE INDEX transactions_receiver_account_idx ON transactions (receiver_account_id);
CREATE INDEX transactions_status_idx ON transactions (status);

-- TRIGGER
CREATE OR REPLACE FUNCTION update_utc_function()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER transactions_update_utc_trigger
BEFORE UPDATE
ON transactions
FOR EACH ROW
EXECUTE PROCEDURE update_utc_function();
--------------- transactions END ----------------

